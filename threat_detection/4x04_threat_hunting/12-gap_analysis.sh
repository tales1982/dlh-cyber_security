echo "    overlaps the advisory's own stated 0x0010 indicator, so bitmask"
echo "    matching alone would false-positive on known-good activity"
echo "  Priority: P1"
echo ""

#============= GAP 3: WMI ================
echo "GAP 3: T1047 WMI Remote Execution"
echo "  Hunt Finding: WmiPrvSE.exe spawned cmd.exe/powershell.exe on all 3"
echo "    target servers within ~30 min of each PsExec session (5-hunt_wmi.sh)"
echo "  Why Missed: Missing rule -- Sysmon Event 1 captured the parent-child"
echo "    relationship, but no rule flagged WmiPrvSE.exe spawning a shell"
echo "  Data Source: Sysmon Event 1 (Process Create), ParentImage field"
echo "  Required Rule: alert when ParentImage=WmiPrvSE.exe AND Image IN"
echo "    (cmd.exe, powershell.exe) -- per HC3's advisory this pattern \"has"
echo "    no legitimate baseline in the observed victim environments,\" so"
echo "    unlike the PsExec/PSRemoting rules this one needs no baseline"
echo "    comparison at all -- the occurrence itself is the indicator"
echo "  Priority: P1"
echo ""

#============= GAP 4: PSRemoting ================
echo "GAP 4: T1021.006 PowerShell Remoting"
echo "  Hunt Finding: Interactive PSRemoting sessions staged the 4x03-confirmed"
echo "    exfiltrator (sync_healthdata.ps1) onto 2 production databases (7-hunt_psremoting.sh)"
echo "  Why Missed: Rule existed but was too specific -- if any PSRemoting"
echo "    monitoring existed, it likely only watched for Enter-PSSession on the"
echo "    admin workstation, not for sessions LANDING on a server from"
echo "    somewhere else, which is the receiving-side wsmprovhost.exe signature"
echo "  Data Source: Sysmon Event 1 (Process Create) on the TARGET host"
echo "  Required Rule: alert when ParentImage=wsmprovhost.exe AND the"
echo "    authenticated user is not in the documented-administrator baseline,"
echo "    OR when a Copy-Item/file-transfer command appears inside a"
echo "    wsmprovhost.exe-parented process"
echo "  Priority: P1 -- this is the staging step that would have given the"
echo "    earliest warning of planned data exfiltration"
echo ""

#============= GAP 5: Service Account Misuse ================
echo "GAP 5: T1078.002 Service Account Misuse"
echo "  Hunt Finding: svc_healthsync authenticated via NTLM from a workstation"
echo "    6 times, violating the authorization matrix in every instance (9-hunt_svcaccount.sh)"
echo "  Why Missed: Missing data correlation, not missing data -- Event 4624"
echo "    was being collected (846 svc_healthsync auth events exist in 14"
echo "    days), but nothing cross-referenced TargetUserName against the"
echo "    service account's documented authorized host"
echo "  Data Source: Windows Event 4624 (Successful Logon)"
echo "  Required Rule: alert when TargetUserName matches ^svc_ AND"
echo "    WorkstationName matches ^WS- (any workstation), OR LogonType IN"
echo "    (2,10,11), OR AuthenticationPackageName=NTLM -- this is the"
echo "    single most reliable rule in this whole gap list: the service"
echo "    account authorization matrix admits ZERO legitimate exceptions"
echo "  Priority: P1 -- highest-confidence, lowest-false-positive rule available"
echo ""

#============= GAP 6: NTLM / Pass-the-Hash ================
