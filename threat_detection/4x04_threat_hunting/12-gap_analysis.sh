#============= GAP 2: LSASS ================
echo "GAP 2: T1003.001 LSASS Credential Access"
echo "  Hunt Finding: debug_tool.exe (path matches HC3 IOC) accessed lsass.exe"
echo "    twice, ~1 week apart, from WS-RECV-03 (6-hunt_credentials.sh)"
echo "  Why Missed: Missing rule -- Sysmon Event 10 was being collected, but"
echo "    no rule evaluated sourceImage against the standard process allowlist"
echo "  Data Source: Sysmon Event 10 (ProcessAccess)"
echo "  Required Rule: alert when TargetImage=lsass.exe AND sourceImage is NOT"
echo "    IN (csrss.exe, services.exe, svchost.exe, MsMpEng.exe, WmiPrvSE.exe,"
echo "    wininit.exe) -- NOT a raw GrantedAccess bitmask check: this dataset"
