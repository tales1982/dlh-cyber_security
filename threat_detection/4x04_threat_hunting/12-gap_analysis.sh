echo "    NTLM instead of the account's documented Kerberos-only policy"
echo "  Why Missed: Missing rule -- this is the SAME underlying Event 4624"
echo "    data as Gap 5, evaluated on a different field (AuthenticationPackageName)"
echo "  Data Source: Windows Event 4624, AuthenticationPackageName field"
echo "  Required Rule: alert on ANY service account authentication using"
echo "    NTLM rather than Kerberos, domain-wide, regardless of source host"
echo "  Priority: P2 -- this rule is evidence-honest, not overclaimed: NTLM"
echo "    usage is consistent with pass-the-hash but does not, by itself,"
echo "    prove a hash (vs. a recovered plaintext password) was used -- see"
