echo "    exact process was being collected the whole time; no Wazuh rule"
echo "    existed to evaluate source host against the admin baseline"
echo "  Data Source: Sysmon Event 1 (Process Create)"
echo "  Required Rule: alert when image/commandLine contains PsExec AND"
echo "    source host != WS-ADMIN-01 OR event time is outside 08:00-18:00 CDT"
